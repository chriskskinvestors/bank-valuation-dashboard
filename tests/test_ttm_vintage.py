class TestOneVintage(unittest.TestCase):
    def test_lark_restated_window_uses_latest_vintage(self):
        ttm = _extract_ttm_value(_facts("EarningsPerShareDiluted", LARK_EPS),
                                 "EarningsPerShareDiluted")
        self.assertAlmostEqual(ttm, 3.28, places=9)

    def test_lark_prior_year_restatement_chain_does_not_merge(self):
        # Full history (deal_comps reads with max_age_years=60): the 2025-11
        # 10-Q itself restated 2024 (its own catch-up) — still not one
        # vintage with the FY2025 10-K.
        facts = _facts("EarningsPerShareDiluted", LARK_EPS_2024 + LARK_EPS)
        self.assertAlmostEqual(
            _extract_ttm_value(facts, "EarningsPerShareDiluted", max_age_years=60), 3.28, places=9)

    def test_lark_dividends_paid_same_rule(self):
        # LARK re-tags no dividend comparative; its EPS restatements are the
        # evidence of the per-share basis change.
        c = "CommonStockDividendsPerShareCashPaid"
        eps = _facts("EarningsPerShareDiluted", LARK_EPS)["facts"]["us-gaap"]
        self.assertAlmostEqual(_extract_ttm_dividend(_facts(c, LARK_DPS_PAID, extra=eps), c),
                               0.82, places=9)
        # Without that evidence the stitched sum is all there is.
        self.assertAlmostEqual(_extract_ttm_dividend(_facts(c, LARK_DPS_PAID), c),
                               0.80, places=9)

    def test_cof_no_restatement_keeps_quarter_sum(self):
        ttm = _extract_ttm_value(_facts("EarningsPerShareDiluted", COF_EPS),
                                 "EarningsPerShareDiluted")
        self.assertAlmostEqual(ttm, 16.70, places=9)

    def test_ccfn_split_after_10k_is_unresolvable(self):
        self.assertIsNone(_extract_ttm_value(_facts("EarningsPerShareDiluted", CCFN_EPS),
                                             "EarningsPerShareDiluted"))

    def test_lsbk_older_filing_already_on_new_basis(self):
        ttm = _extract_ttm_value(_facts("EarningsPerShareDiluted", LSBK_EPS),
                                 "EarningsPerShareDiluted")
        self.assertAlmostEqual(ttm, 1.14, places=9)

    def test_bbt_catch_up_restatement_keeps_quarter_sum(self):
        ttm = _extract_ttm_value(_facts("EarningsPerShareDiluted", BBT_EPS),
                                 "EarningsPerShareDiluted")
        self.assertAlmostEqual(ttm, 1.91, places=9)

    def test_botj_retagging_noise_is_not_a_restatement(self):
        ttm = _extract_ttm_value(_facts("NetIncomeLoss", BOTJ_NI, "USD"), "NetIncomeLoss")
        self.assertAlmostEqual(ttm, 11_489_000, places=3)


class TestDividendAnchor(unittest.TestCase):
    C = "CommonStockDividendsPerShareDeclared"

    def test_bafn_suspension_is_zero(self):
        facts = _facts(self.C, BAFN_DPS, extra=BAFN_ASSETS)
        self.assertEqual(_extract_ttm_dividend(facts, self.C, as_of=_recent("2026-06-30")), 0.0)

    def test_bhrb_annual_only_tagger_is_unknown(self):
        facts = _facts(self.C, BHRB_DPS, extra=BHRB_ASSETS)
        self.assertIsNone(_extract_ttm_dividend(facts, self.C, as_of=_recent("2026-06-30")))

    def test_banc_retag_inside_the_year_keeps_044(self):
        c = self.C
        self.assertAlmostEqual(
            _extract_ttm_dividend(_facts(c, BANC_DPS), c, as_of=_recent("2026-06-30")),
            0.44, places=9)

    def test_current_payer_unchanged(self):
        # COLB-shape quarterly tags through the newest filing's period end.
        rows = [(s, e, v, "10-Q", f, "a") for s, e, v, f in [
            ("2025-07-01", "2025-09-30", 0.36, "2025-11-06"),
            ("2025-10-01", "2025-12-31", 0.37, "2026-05-05"),
            ("2026-01-01", "2026-03-31", 0.37, "2026-05-05"),
            ("2026-04-01", "2026-06-30", 0.37, "2026-08-04")]]
        facts = _facts(self.C, rows)
        self.assertAlmostEqual(
            _extract_ttm_dividend(facts, self.C, as_of=_recent("2026-06-30")), 1.47, places=9)
        self.assertAlmostEqual(_extract_ttm_dividend(facts, self.C), 1.47, places=9)

    def test_annual_at_newest_10k_unchanged(self):
        facts = _facts(self.C, BHRB_DPS)
        self.assertAlmostEqual(
            _extract_ttm_dividend(facts, self.C, as_of=_recent("2025-12-31")), 2.20, places=9)


